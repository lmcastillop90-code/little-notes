export type Key = keyof typeof en;
export const dict = { en, vi };

/** Returns t(key) for the primary language, and t2(key) for the secondary line when lang === 'both'. */
export function makeT(lang: Lang) {
  const primary = lang === 'vi' ? vi : en;
  const secondary = lang === 'both' ? vi : null;
  const t = (k: Key, vars?: Record<string, string | number>) => interpolate(primary[k], vars);
  const t2 = (k: Key, vars?: Record<string, string | number>) => (secondary ? interpolate(secondary[k], vars) : '');
  const tb = (k: Key, vars?: Record<string, string | number>) => (secondary ? `${t(k, vars)} · ${t2(k, vars)}` : t(k, vars));
  return { t, t2, tb, primary: (lang === 'vi' ? 'vi' : 'en') as 'en' | 'vi' };
}

function interpolate(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

